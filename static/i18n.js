function fill(str, vars) {
  return vars ? str.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : str;
}
function t(key, vars) {
  const one = vars && Number(vars.n) === 1;
  let str;
  if (LANG === "en") str = (one && EN_ONE[key]) || EN[key] || key;
  else str = (one && SV_ONE[key]) || SV[key] || key;
  return fill(str, vars);
}
