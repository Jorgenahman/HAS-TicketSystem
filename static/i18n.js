function tv(value) { return LANG === "en" && value in DATA_EN ? DATA_EN[value] : value; }
function tErr(msg) {
  if (!msg || LANG !== "en") return msg;
  if (ERR_EN[msg]) return ERR_EN[msg];
  for (const [rx, rep] of ERR_EN_PATTERNS) if (rx.test(msg)) return msg.replace(rx, rep);
  return msg;
}
